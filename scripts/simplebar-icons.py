#!/usr/bin/env python3
"""Regenerate src/icons/simple_bar.rs from a simple-bar checkout.

    scripts/simplebar-icons.py [SIMPLE_BAR_DIR]

SIMPLE_BAR_DIR defaults to Übersicht's widget folder. It reads the icon
library (lib/components/icons) and the app → icon map (lib/app-icons.js),
turns each icon's JSX into plain SVG markup, and writes one Rust file of
static tables. simple-bar is MIT licensed (src/icons/SIMPLE-BAR-LICENSE).
"""

import os
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    "~/Library/Application Support/Übersicht/widgets/simple-bar"
)
icons_dir = os.path.join(src, "lib/components/icons")
out = os.path.join(os.path.dirname(__file__), "..", "src/icons/simple_bar.rs")

exports = dict(
    re.findall(
        r'export const (\w+) = React\.lazy\(\s*\(\) => import\("\./library/([\w-]+)\.jsx"\)',
        open(os.path.join(icons_dir, "icons.jsx")).read(),
    )
)

ATTRS = {"fillRule": "fill-rule", "clipRule": "clip-rule", "fillOpacity": "fill-opacity", "strokeWidth": "stroke-width"}


def markup(jsx):
    """The SVG inside <Icon …>…</Icon>, and the Icon's width and height."""
    m = re.search(r"<Icon\b([^>]*)>(.*)</Icon>", jsx, re.S)
    if not m:
        raise ValueError("no <Icon> element")
    props, body = m.groups()
    w = re.search(r"width=\{?\"?(\d+)", props)
    h = re.search(r"height=\{?\"?(\d+)", props)
    body = re.sub(r'\s(className|id)=("[^"]*"|\{[^}]*\})', "", body)
    body = re.sub(r'\sfill="var\([^)]*\)"', "", body)  # theme colours: the tint applies
    for a, b in ATTRS.items():
        body = body.replace(f" {a}=", f" {b}=")
    body = re.sub(r"(\w[\w-]*)=\{([\d.]+)\}", r'\1="\2"', body)
    if "{" in body:
        raise ValueError("JSX expression left: " + body[body.index("{") : body.index("{") + 40])
    body = re.sub(r"\s+", " ", body).replace("> <", "><").strip()
    return int(w.group(1)) if w else 24, int(h.group(1)) if h else 24, body


icons = []
for name, file in sorted(exports.items()):
    w, h, body = markup(open(os.path.join(icons_dir, "library", file + ".jsx")).read())
    icons.append((name, w, h, body))

apps = re.findall(
    r'^\s*(?:"([^"]+)"|(\w+)):\s*Icons\.(\w+),', open(os.path.join(src, "lib/app-icons.js")).read(), re.M
)
apps = sorted(((a or b), icon) for a, b, icon in apps if icon in exports)


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


with open(out, "w") as f:
    f.write("// Generated by scripts/simplebar-icons.py from simple-bar's icon library\n")
    f.write("// (MIT licence, Jean Tinland: see SIMPLE-BAR-LICENSE). Do not edit.\n\n")
    f.write("/// (name, viewBox width, viewBox height, SVG markup), sorted by name.\n")
    f.write("pub static ICONS: &[(&str, u16, u16, &str)] = &[\n")
    for name, w, h, body in icons:
        f.write(f"    ({rs(name)}, {w}, {h}, {rs(body)}),\n")
    f.write("];\n\n/// (app name, icon name), sorted by app name.\n")
    f.write("pub static APPS: &[(&str, &str)] = &[\n")
    for app, icon in apps:
        f.write(f"    ({rs(app)}, {rs(icon)}),\n")
    f.write("];\n")
print(f"{len(icons)} icons, {len(apps)} apps -> {os.path.normpath(out)}")
